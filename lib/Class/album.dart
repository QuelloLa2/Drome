class Album {

  final String nameAlbum;
  final String idAlbum;

  final String genre;
  final int year;

  final String idArtist;
  final int songCount;

  Album({

    required this.nameAlbum,
    required this.idAlbum,

    required this.genre,
    required this.year,

    required this.idArtist,
    required this.songCount
  });

}